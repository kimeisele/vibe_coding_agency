from pathlib import Path
from datetime import datetime
from typing import Dict, Tuple

from config.settings import PROJECTS_DIR

def get_project_status(project_name: str) -> Dict[str, str]:
    """
    Checks the completion status of a project's protocol files.
    """
    project_path = PROJECTS_DIR / project_name
    if not project_path.exists():
        raise FileNotFoundError(f"Project not found: {project_name}")

    status = {}
    protocol_files = [
        "01_semantic_understanding.md",
        "02_knowledge_acquisition.md",
        "03_data_driven_validation.md"
    ]

    for filename in protocol_files:
        file_path = project_path / filename
        if not file_path.exists():
            status[filename] = "Not started"
            continue

        content = file_path.read_text()
        if "[FILL:" in content:
            status[filename] = "In progress (has [FILL:...])"
        elif "[ ]" in content:
             status[filename] = "In progress (has [ ] todos)"
        else:
            status[filename] = "Complete"
            
    return status


def generate_report_template(project_name: str) -> Tuple[str, bool]:
    """
    Generates a final report by assembling the filled-out protocols.
    Also performs validation checks.
    """
    project_path = PROJECTS_DIR / project_name
    if not project_path.exists():
        raise FileNotFoundError(f"Project not found: {project_name}")

    protocols = {}
    protocol_filenames = [
        "01_semantic_understanding.md",
        "02_knowledge_acquisition.md",
        "03_data_driven_validation.md"
    ]
    for filename in protocol_filenames:
        file_path = project_path / filename
        if file_path.exists():
            protocols[filename] = file_path.read_text()
        else:
            protocols[filename] = f"[MISSING FILE: {filename}]"

    # Validation checks
    has_sources = any("http" in p for p in protocols.values())
    has_tool_outputs = "RAW OUTPUT:" in protocols.get("03_data_driven_validation.md", "")
    no_fills = not any("[FILL:" in p for p in protocols.values())
    no_speculation = not any(
        word in p.lower()
        for p in protocols.values()
        for word in ["should work", "probably", "i think"]
    )
    all_passed = all([has_sources, has_tool_outputs, no_fills, no_speculation])

    # Assemble the report
    report_content = f"""# Technical Assessment Report
Project: {project_name}
Date: {datetime.now().strftime("%Y-%m-%d")}
Generated by: Agency CLI

---
## Executive Summary
[HUMAN: Write 2-3 sentence summary of situation + recommendation]
---
## Methodology
...
---
## Analysis

### Understanding Phase
{protocols.get("01_semantic_understanding.md", "[Missing]")}
---
### Research Findings  
{protocols.get("02_knowledge_acquisition.md", "[Missing]")}
---
### Technical Validation
{protocols.get("03_data_driven_validation.md", "[Missing]")}
---
## Recommendations
[HUMAN: Based on all above, write specific recommendations]
...
"""
    return report_content, all_passed

